// ใส่ข้อความลงหน้าเมนู (data-t="menu.xxx" หรือ "a|b" = สองบรรทัด)
document.addEventListener('DOMContentLoaded',()=>{
  document.querySelectorAll('[data-t]').forEach(el=>{
    const ks=el.dataset.t.split('|').map(k=>k.split('.').reduce((o,x)=>o&&o[x],TEXTS));
    el.replaceChildren(...ks.flatMap((t,i)=>i?[document.createElement('br'),document.createTextNode(t)]:[document.createTextNode(t)]));
  });
  document.title=TEXTS.menu.title;
});
